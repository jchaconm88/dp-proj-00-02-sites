/**
 * Imprime un icono SVG.
 *
 * @param string $name      Clave del icono.
 * @param string $class     Clases CSS adicionales.
 * @param int    $size      Tamaño en px (ancho/alto).
 */
function mi_cliente_storefront_icon( $name, $class = '', $size = 24 ) {
	$paths   = mi_cliente_storefront_icon_paths();
	$path    = isset( $paths[ $name ] ) ? $paths[ $name ] : $paths['category'];
	$classes = trim( 'dsam-icon ' . $class );
	printf(
		'<svg class="%1$s" xmlns="http://www.w3.org/2000/svg" width="%2$d" height="%2$d" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" focusable="false">%3$s</svg>',
		esc_attr( $classes ),
		max( 12, (int) $size ),
		$path // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- paths estáticos controlados.
	);
}
